export function t(language: Language, text: string): string {
  return language === 'en' ? en[text] ?? text : text;
}

export function displayStatus(language: Language, value: string): string {
  if (language === 'zh') return value;
  return ({ idle: 'Idle', running: 'Running', waiting: 'Waiting', interrupted: 'Interrupted', queued: 'Queued', succeeded: 'Succeeded', failed: 'Failed', done: 'Done', error: 'Error' } as Record<string, string>)[value] ?? value;
}

export function eventLabel(language: Language, label: string): string {
  if (language === 'zh') return label;
  if (label.startsWith('媒体图片：')) return `Image generation: ${displayStatus(language, label.slice('媒体图片：'.length))}`;
  if (label.startsWith('媒体视频：')) return `Video generation: ${displayStatus(language, label.slice('媒体视频：'.length))}`;
  const agentAllowed = /^Agent「(.+)」默认允许工具$/.exec(label);
  if (agentAllowed) return `Agent “${agentAllowed[1]}” allowed this tool by default`;
  return t(language, label);
}
